export function pickQuote(excludeIndices = []) {
  const available = quotes.map((_, i) => i).filter((i) => !excludeIndices.includes(i))
  const pool = available.length > 0 ? available : quotes.map((_, i) => i)
  const idx = pool[Math.floor(Math.random() * pool.length)]
  return { index: idx, quote: quotes[idx] }
}
